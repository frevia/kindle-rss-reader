"""Generate the read-only lookup table from the pinned Apache-2.0 Rime dictionary."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "third_party/pinyin"


def main():
    manifest = json.loads((ROOT / "SOURCE.json").read_text())
    for name, spec in manifest["files"].items():
        if hashlib.sha256((ROOT / name).read_bytes()).hexdigest() != spec["sha256"]:
            raise RuntimeError(f"Dictionary source changed: {name}")
    entries = {}
    for line in (ROOT / "pinyin_simp.dict.yaml").read_text().splitlines():
        if "\t" not in line or line.startswith("#"):
            continue
        text, pinyin, weight = line.split("\t")
        key = pinyin.replace(" ", "")
        assert key and all("a" <= char <= "z" for char in key)
        assert 0 < len(text) <= 4
        entries[key, text] = max(int(weight), entries.get((key, text), 0))
    rows = sorted(entries, key=lambda item: (item[0], -entries[item], item[1]))
    output = "// Generated by tools/generate_pinyin.py; Rime pinyin-simp, Apache-2.0.\n"
    output += "// Space-separated syllables are joined; candidates retain descending source frequency.\n"
    output += "static constexpr PinyinEntry pinyin_entries[] = {\n"
    output += "".join("{" + json.dumps(key) + "," + json.dumps(text, ensure_ascii=False) + "},\n" for key, text in rows)
    output += "};\n"
    (ROOT / "table.h").write_text(output)
    print(f"Generated {len(rows)} pinyin candidates")


if __name__ == "__main__":
    main()
